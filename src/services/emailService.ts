import { Document } from '../types';

export const sendAnalysisByEmail = async (
  document: Document,
  recipientEmail: string
): Promise<void> => {
  if (!document.analysis) {
    throw new Error('No analysis available to send');
  }

  const analysis = document.analysis;

  const htmlContent = `
    <!DOCTYPE html>
    <html>
    <head>
      <style>
        body { font-family: Arial, sans-serif; line-height: 1.6; color: #333; }
        .container { max-width: 600px; margin: 0 auto; padding: 20px; }
        .header { background: #2563eb; color: white; padding: 20px; text-align: center; border-radius: 5px 5px 0 0; }
        .content { background: #f9fafb; padding: 20px; border-radius: 0 0 5px 5px; }
        .score { font-size: 48px; font-weight: bold; text-align: center; padding: 20px; }
        .score-high { color: #dc2626; }
        .score-medium { color: #d97706; }
        .score-low { color: #16a34a; }
        .risk { margin: 15px 0; padding: 15px; border-left: 4px solid; border-radius: 4px; }
        .risk-high { background: #fee2e2; border-color: #dc2626; }
        .risk-medium { background: #fef3c7; border-color: #d97706; }
        .risk-low { background: #dcfce7; border-color: #16a34a; }
        .category { margin: 10px 0; }
        .footer { text-align: center; margin-top: 20px; padding-top: 20px; border-top: 1px solid #e5e7eb; color: #6b7280; font-size: 12px; }
      </style>
    </head>
    <body>
      <div class="container">
        <div class="header">
          <h1>IndiaLawAI Compliance Report</h1>
        </div>
        <div class="content">
          <h2>${document.name}</h2>
          <p><strong>Uploaded:</strong> ${new Date(document.uploadedAt).toLocaleString()}</p>
          
          <div class="score ${analysis.indiaLawScore >= 75 ? 'score-low' : analysis.indiaLawScore >= 50 ? 'score-medium' : 'score-high'}">
            ${analysis.indiaLawScore}/100
          </div>
          
          <h3>Risk Summary</h3>
          <p>High: ${analysis.riskSummary.high} | Medium: ${analysis.riskSummary.medium} | Low: ${analysis.riskSummary.low}</p>
          
          <h3>Category Scores</h3>
          ${analysis.categoryScores.map(cat => `
            <div class="category">
              <strong>${cat.category}:</strong> ${cat.score}%
            </div>
          `).join('')}
          
          ${analysis.risks.length > 0 ? '<h3>Identified Risks</h3>' : ''}
          ${analysis.risks.slice(0, 5).map(risk => `
            <div class="risk risk-${risk.level.toLowerCase()}">
              <strong>${risk.level} Risk - ${risk.category}</strong><br/>
              <em>${risk.description}</em><br/>
              <strong>Citation:</strong> ${risk.citation}<br/>
              <strong>Recommendation:</strong> ${risk.recommendation}
            </div>
          `).join('')}
          
          ${analysis.risks.length > 5 ? `<p><em>... and ${analysis.risks.length - 5} more risks. View full report for details.</em></p>` : ''}
          
          <div class="footer">
            <p>Generated by IndiaLawAI on ${new Date().toLocaleString()}</p>
            <p>For more details, visit IndiaLawAI</p>
          </div>
        </div>
      </div>
    </body>
    </html>
  `;

  const subject = `IndiaLawAI Report: ${document.name}`;

  try {
    // Try backend email service first
    const response = await fetch('http://localhost:3001/send-report', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        to: recipientEmail,
        subject,
        html: htmlContent,
      }),
    });

    const result = await response.json();
    
    if (!result.success) {
      throw new Error(result.message || 'Failed to send email');
    }
  } catch (error) {
    console.error('Backend email failed, falling back to mailto:', error);
    
    // Fallback to mailto
    const plainTextBody = `
Please find the compliance analysis for ${document.name}:

IndiaLaw Score: ${analysis.indiaLawScore}/100

Risk Summary:
- High: ${analysis.riskSummary.high}
- Medium: ${analysis.riskSummary.medium}
- Low: ${analysis.riskSummary.low}

Category Scores:
${analysis.categoryScores.map(cat => `- ${cat.category}: ${cat.score}%`).join('\n')}

For detailed analysis, please visit IndiaLawAI
    `;

    const mailtoLink = `mailto:${recipientEmail}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(plainTextBody)}`;
    window.location.href = mailtoLink;
  }
};
