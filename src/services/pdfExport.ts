export const exportAnalysisToPDF = async (
  document: Document,
  targetLanguage: string = 'en'
): Promise<void> => {
  if (!document.analysis) {
    alert('No analysis available to export');
    return;
  }

  const doc = new jsPDF();
  let analysis = document.analysis;

  // Translate if not English
  if (targetLanguage !== 'en') {
    try {
      const translated = await translateAnalysisForPDF(analysis, targetLanguage);
      analysis = { ...analysis, ...translated };
    } catch (error) {
      console.error('Translation failed, using English:', error);
      // Continue with English
    }
  }

  // Get translations
  const t = PDF_TRANSLATIONS[targetLanguage] || {};

  // Title
  doc.setFontSize(20);
  doc.text(
    t['IndiaLawAI Compliance Report'] || 'IndiaLawAI Compliance Report',
    105, 20, { align: 'center' }
  );

  // Document Info
  doc.setFontSize(12);
  doc.text(`${t['Document'] || 'Document'}: ${document.name}`, 14, 35);
  doc.text(`${t['Uploaded'] || 'Uploaded'}: ${new Date(document.uploadedAt).toLocaleString()}`, 14, 42);
  doc.text(`${t['Processing Time'] || 'Processing Time'}: ${analysis.processingTime}s`, 14, 49);

  let yPos = 60;

  // IndiaLaw Score
  doc.setFontSize(16);
  doc.text(t['IndiaLaw Score'] || 'IndiaLaw Score', 14, yPos);
  yPos += 8;
  doc.setFontSize(40);
  doc.setTextColor(analysis.indiaLawScore < 50 ? 239 : analysis.indiaLawScore < 75 ? 245 : 34);
  doc.text(`${analysis.indiaLawScore}/100`, 105, yPos, { align: 'center' });
  doc.setTextColor(0);
  yPos += 15;

  // Risk Summary (keep risk levels in English for clarity)
  doc.setFontSize(16);
  doc.text(t['Risk Summary'] || 'Risk Summary', 14, yPos);
  yPos += 8;
  
  autoTable(doc, {
    startY: yPos,
    head: [[t['Risk Level'] || 'Risk Level', 'Count']],
    body: [
      ['HIGH', analysis.riskSummary.high.toString()],
      ['MEDIUM', analysis.riskSummary.medium.toString()],
      ['LOW', analysis.riskSummary.low.toString()],
    ],
    theme: 'striped',
    headStyles: { fillColor: [59, 130, 246] },
    styles: {
      fillColor: [254, 226, 226],
    },
    didParseCell: (data) => {
      if (data.row.index === 0) {
        data.cell.styles.fillColor = [254, 226, 226];
      } else if (data.row.index === 1) {
        data.cell.styles.fillColor = [254, 243, 199];
      } else if (data.row.index === 2) {
        data.cell.styles.fillColor = [220, 252, 231];
      }
    },
  });

  yPos = (doc as any).lastAutoTable.finalY + 15;

  // Category Scores
  doc.setFontSize(16);
  doc.text(t['Compliance Score by Category'] || 'Compliance Score by Category', 14, yPos);
  yPos += 8;

  autoTable(doc, {
    startY: yPos,
    head: [[t['Category'] || 'Category', t['Score (%)'] || 'Score (%)']],
    body: analysis.categoryScores.map(cat => [cat.category, cat.score.toString()]),
    theme: 'striped',
    headStyles: { fillColor: [59, 130, 246] },
  });

  yPos = (doc as any).lastAutoTable.finalY + 15;

  // Risks
  if (analysis.risks.length > 0) {
    doc.setFontSize(16);
    doc.text(t['Identified Risks'] || 'Identified Risks', 14, yPos);
    yPos += 8;

    autoTable(doc, {
      startY: yPos,
      head: [['Level', 'Category', 'Description', 'Citation']],
      body: analysis.risks.map(risk => [
        risk.level,
        risk.category,
        risk.description.substring(0, 50) + (risk.description.length > 50 ? '...' : ''),
        risk.citation,
      ]),
      theme: 'striped',
      headStyles: { fillColor: [59, 130, 246] },
      styles: { fontSize: 8 },
    });

    yPos = (doc as any).lastAutoTable.finalY + 15;
  }

  // Footer
  doc.setFontSize(10);
  doc.setTextColor(128);
  doc.text(
    `${t['Generated by IndiaLawAI on'] || 'Generated by IndiaLawAI on'} ${new Date().toLocaleString()}`,
    105,
    doc.internal.pageSize.height - 10,
    { align: 'center' }
  );

  // Save the PDF
  doc.save(`${document.name.replace(/\.[^/.]+$/, '')}_Analysis_${targetLanguage}.pdf`);
};
